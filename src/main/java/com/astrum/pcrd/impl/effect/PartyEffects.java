    /**
     * {@return every <b>mechanic</b> effect this mod registers, i.e. everything that is not a party slot}
     *
     * <p>What the sprite test and the icon generator enumerate. A method rather than a field, and a fresh
     * list each call, for the same reason {@link #holders()} is.
     *
     * <p>Deliberately <b>not</b> derived by subtraction from the registry: this list is the declaration, so
     * an effect registered but forgotten here fails {@code EffectSpriteResourceTest} rather than silently
     * shipping a purple checkerboard.
     */
    public static List<DeferredHolder<MobEffect, MobEffect>> mechanicHolders() {
        return List.of(ATTACK_BUFF, DEFENCE_DOWN, ATTACK_AREA, PHYS_DEFENCE, MAGIC_DEFENCE, HASTE,
                PANIC, CHARGE_RATE, SHIELD, MAGIC_DEFENCE_DOWN, MAGIC_ATTACK_AREA, SPIRIT, COUNTER,
                CHARGE_REGEN, PHYS_DEFENCE_FLAT, TAUNT, PHYS_IMMUNITY, CONTROL_IMMUNITY,
                // The two named states are mechanics too: each needs a sprite or its bar row is the purple
                // checkerboard, and each is read by a real predicate (the hook gate / the state itself).
                WIND_BLADE, TEA_POT,
                // 矛依未's 「标记 ID 125」: a third named state, read by her second loop's two gated branches.
                MARKER_125,
                // The timed crit-damage buff: it carries a real attribute modifier, so it needs a sprite like every
                // other mechanic (the sprite test's manifest is this list).
                CRIT_DAMAGE_UP,
                // The crit-chance twin and the tally-scaled charge regen: both carry real mechanics (an attribute
                // modifier and a per-tick gauge credit), so both need a sprite like every other mechanic.
                CRIT_CHANCE_UP, CHARGE_COUNTER,
                // The two victim-side crit debuffs. They carry real attribute modifiers on the body that was hit,
                // so they need a sprite like every other mechanic — and they are *not* in shownHolders(): a debuff on
                // a mob has no player bar to appear on.
                CRIT_CHANCE_DOWN, CRIT_DAMAGE_DOWN);
    }

    /**
     * {@return the mechanic effects that are <b>shown</b> in vanilla's effect lists, i.e. the ones a player is
     * meant to read}
     *
     * <h2>Why this is a second list and not a subtraction</h2>
     * {@link #mechanicHolders()} answers "what exists" — it is the sprite generator's and the sprite test's
     * manifest, and every effect needs a picture whether or not it is drawn. This one answers "what is
     * displayed", which the human has now changed twice:
     *
     * <ul>
     *   <li>「药水栏不是把每个通用效果都显示出来」 — the fourteen mechanics are input to the damage maths, not
     *       statuses a player counts, so they are hidden ({@code HiddenEffectClient});</li>
     *   <li>「这种有层数，且层数会被消耗的效果，做成会显示在药水栏，使用等级来计数，计数越多，药水效果等级越高」
     *       — 计数 is the exception. Its amplifier <em>is</em> the stack count, so vanilla's own effect-level
     *       suffix prints the number for free, and 雪菲 reads those stacks as damage. A player needs to see
     *       them, and hiding the one effect whose whole point is a visible tally was the wrong reading of the
     *       first sentence.</li>
     * </ul>
     *
     * <p>A subtraction ({@code mechanicHolders() minus COUNTER}) was rejected for the reason the method above
     * gives: the declaration is the point, and a list computed by removing things silently accepts a new
     * effect that nobody decided about.
     */
    public static List<DeferredHolder<MobEffect, MobEffect>> shownHolders() {
        // <b>Empty, and that is the ruling.</b> 计数 used to be the one exception, so a player could read the
        // tally on her bar. The human then watched 雪菲 fight and reported two rows for one event:
        // 「冰龙之印和计数是同一个东西？我怎么看他们cd一致，同时触发」 — the skill row and the tally it
        // granted. He asked for one: 「只留冰龙之印」.
        //
        // <p>So the tally is hidden again and the SKILL row carries the number instead: its amplifier is
        // {@code Counters.countOf - 1} (see {@code SkillEntryBuffs.amplifierFor}), so vanilla prints
        // 「冰龙之印 IV」 — the count is still visible, on the row a player can also name and see the icon of.
        // Nothing is lost and the duplicate is gone.
        //
        // <p>Kept as an empty list rather than deleted: it is the declaration the hider reads, and the next
        // effect that needs to be visible belongs here as one more entry.
        return List.of();
    }

