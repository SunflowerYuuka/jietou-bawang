/**
 * Every {@code MobEffect} this mod registers: the five party slots, and the effects that carry an
 * attribute modifier or a mechanic.
 *
 * <h2>Registration, not mechanics</h2>
 * The {@code MobEffect}s for the party slots are inert markers; the server-side lifecycle lives in
 * {@link PartyBuffs} and the client-side icon/name in {@code impl.client.PartyEffectClient}. This class is
 * only the wiring, so the classes that know the ids stay free of the registry and are testable without a
 * game.
 *
 * <h2>Three families, and why they are in one register</h2>
 * <ul>
 *   <li><b>The five party slots</b> ({@code astrum:party_1..5}) — inert. Five separate registrations
 *       because vanilla keys a player's effects by type, so one shared type would merge five characters
 *       into one HUD entry. See {@link PartyEffectSlots}.</li>
 *   <li><b>The skill entries</b> ({@code astrum:skill/<character>/<skill>}) — one type <b>per skill</b>, inert.
 *       They are a different question from the party runes (「我刚放了什么」 versus 「谁和我在一起」), which is why
 *       they are a separate family rather than {@code int} amplifiers on the existing ones. One type per skill
 *       is what lets two of one character's skills be on the bar at once — see {@link SkillEffectTypes} for the
 *       defect that named it and for how 91 types come to exist without a 91-line literal.</li>
 *   <li><b>The mechanic effects</b> — {@code attack_buff}, {@code defence_down} and, since the generic
 *       effect kernel, {@code attack_area}, {@code phys_defence}, {@code magic_defence}, {@code haste},
 *       {@code panic} and {@code charge_rate}. Each is a real registered effect so {@code /effect give}
 *       works and the HUD shows it, and each carries its own substance: an attribute modifier for
 *       {@code attack_buff} / {@code defence_down} / {@code attack_area} / {@code haste}, a damage-path
 *       read for the two defence buffs, a per-instance tick for {@code panic}, and a charge-path read for
 *       {@code charge_rate}.</li>
 * </ul>
 *
 * <p>One {@link DeferredRegister} for both families because a mod has one {@code MOB_EFFECT} register; the
 * split above is about lifecycle, not about registry.
 *
 * <h2>Every effect needs a picture, but not every family needs a <em>file</em></h2>
 * Vanilla's {@code mob_effects} atlas indexes {@code assets/<ns>/textures/mob_effect/<path>.png} per effect
 * id, and a missing file is Minecraft's purple missing-texture checker — the defect the human photographed
 * twice. So every effect's icon has to resolve <em>somehow</em>, and the two ways this mod does it are:
 *
 * <ul>
 *   <li><b>a committed PNG</b> for the mechanic family, derived from the official skill icons by
 *       {@code tools/gen_effect_icons.py} / {@code gen_tinted_icons.py}, plus five pure-procedural runes for the
 *       party slots. {@code EffectSpriteResourceTest} enumerates {@link #mechanicHolders()} and
 *       {@link PartyEffectSlots#ids()} and fails if any of those files is unreachable.</li>
 *   <li><b>an {@code IClientMobEffectExtensions} hook</b> for the skill entries, which draw from the pack's own
 *       skill icons and never let vanilla's sprite be consulted at all
 *       ({@code SkillEntryClient} answers {@code true} unconditionally). The family still ships <b>one
 *       self-drawn placeholder per type</b> ({@code textures/mob_effect/skill/<character>/<skill>.png},
 *       generated by {@code tools/gen_skill_effect_types.py}): JEI and any other atlas consumer ask for the
 *       sprite by registry id, and a missing one is the magenta checkerboard. So the split is
 *       <b>jar = placeholder, pack = the real skill icon</b>, and the extension picks the real one when the
 *       pack is installed.</li>
 * </ul>
 */
