    /**
     * {@return {@code holder} as an optional {@link Holder}, empty when the registry is not up}
     *
     * <p>One helper for the eight lookups above: {@code isBound()} is the only safe question to ask a
     * {@code DeferredHolder} before the {@code RegisterEvent} has run, and asking it in eight places invites
     * one of them to forget.
     */
    private static Optional<Holder<MobEffect>> bound(DeferredHolder<MobEffect, MobEffect> holder) {
        return holder.isBound() ? Optional.of(holder) : Optional.empty();
    }

