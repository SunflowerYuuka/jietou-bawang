    /**
     * {@return the slot of a registered effect, empty for an effect this mod did not register}
     *
     * <p>Identity, not id parsing: the five objects are constructed once by the registry, so a
     * reference comparison is exact and needs no registry lookup (which is what lets it be called on
     * the client for a hovered effect without touching {@code BuiltInRegistries}).
     */
    public static OptionalInt slotOf(MobEffect effect) {
        List<DeferredHolder<MobEffect, MobEffect>> holders = holders();
        for (int slot = 0; slot < holders.size(); slot++) {
            if (holders.get(slot).value() == effect) {
                return OptionalInt.of(slot);
            }
        }
        return OptionalInt.empty();
    }

    /** Registers every effect on the mod bus, and the one attribute they write to. */
    public static void register(IEventBus modBus) {
        // 魔法攻击力 is registered here rather than from Astrum for the reason the effects are wired from
        // Attachments: Astrum stays wiring-only and short (plan R1). The pairing is genuine — the attribute
        // exists for these effects to raise, and MAGIC_ATTACK_AREA cannot apply a modifier without it.
        // Attributes come before effects in NeoForge's registry order, so the holder is bound by the time
        // MagicAttackAreaEffect's constructor reads it.
        MagicAttack.register(modBus);
        // 暴击's two attributes go through the same door and for the same reason: they are stats nothing in
        // the registry carries, and the effects that will raise them are registered three lines below.
        Crit.register(modBus);
        MOB_EFFECTS.register(modBus);
    }
